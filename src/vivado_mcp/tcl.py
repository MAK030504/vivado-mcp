def _tcl_path(path: Path) -> str:
    """Return a path string suitable for Tcl on Windows and Linux.

    Vivado on Windows accepts forward slashes. Always normalize separators so
    Windows-style paths remain safe even when this code runs on Linux (for
    example in CI while generating Tcl for a remote Windows Vivado).
    """
    return str(path.expanduser()).replace("\\", "/")
