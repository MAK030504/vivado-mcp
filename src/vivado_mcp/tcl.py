            'puts "VIVADO_MCP_STATUS=ERROR"',
            'puts "VIVADO_MCP_BITSTREAM_STATUS=failed"',
            'puts "VIVADO_MCP_BITSTREAM_ERROR=Top module is not set on sources_1"',
            "close_project",
            "exit 1",
            "}",
            'puts "VIVADO_MCP_BITSTREAM_TOP=$_mcp_top"',
            "if {[llength [get_runs -quiet synth_1]] == 0} {",
            'puts "VIVADO_MCP_STATUS=ERROR"',
