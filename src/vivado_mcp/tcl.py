def build_run_implementation_tcl(
    *,
    xpr_path: Path,
    report_dir: Path,
) -> str:
    """Build Tcl for implementation + post-route reports (Vivado 2018.2+).

    Requires ``synth_1`` to have completed. Ensures ``impl_1``, launches it,
    waits, then writes implementation utilization and timing-summary reports.
    Never opens the GUI.
    """
